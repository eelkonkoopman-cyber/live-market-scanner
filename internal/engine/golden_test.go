// goldRestart is the second scenario: an engine started late in the pre-market
// (so its pre-market high is not complete), a mid-day restart into the regular
// session, and a new day that begins without the market ever having closed.
func goldRestart(tb testing.TB, rec *goldRec) *goldSim {
	wins := []goldWin{
		{goldSec(20, 4, 8, 0), goldSec(20, 4, 14, 0)},
		{goldSec(20, 9, 26, 0), goldSec(20, 9, 40, 0)},
		{goldSec(20, 11, 0, 0), goldSec(20, 11, 10, 0)},
		{goldSec(20, 15, 59, 0), goldSec(20, 16, 3, 0)},
		{goldSec(21, 3, 59, 0), goldSec(21, 4, 3, 0)},
	}
	const n = 160
	mkt := newGoldMarket(goldMarketCfg{seed: goldSeed + 7, n: n, minutes: goldMinutes(wins)})
	mkt.scriptDildo(3, goldSec(20, 9, 26, 0)/60, 3, false, 0.12, 0.004, 9)
	mkt.scriptClimax(8, goldSec(20, 9, 36, 0)/60, 3, 0)
	d := newGoldDriver(tb, func() Options {
		o := goldOptions()
		o.Baseline = mkt.baseline(goldSeed+110, 0)
		return o
	}(), goldMs(20, 4, 7, 20, 0))
	s := &goldSim{tb: tb, d: d, mkt: mkt, rec: rec, rng: newGoldRand(goldSeed+7, 999_999), wins: wins, pSparse: 0.12}
	span := func(day, h1, m1, s1, h2, m2, s2 int) goldSpan {
		return goldSpan{goldSec(day, h1, m1, s1), goldSec(day, h2, m2, s2)}
	}
	s.dense = []goldSpan{
		span(20, 4, 8, 0, 4, 9, 0), span(20, 9, 29, 40, 9, 30, 20), span(20, 9, 34, 0, 9, 35, 0),
		span(20, 11, 0, 0, 11, 1, 0), span(20, 15, 59, 40, 16, 0, 20), span(21, 3, 59, 40, 4, 0, 40),
	}
	same := func(int) float64 { return 1 }
	s.op(goldMs(20, 4, 7, 40, 0), "seed", func() { s.opSeed(func(i int) bool { return i%9 != 4 }, same) })
	s.op(goldMs(20, 4, 7, 50, 0), "late pre", func() { // 4 minutes after the open: the pre-market high will not be complete
		s.d.e.SetSecTypes(mkt.types(goldSeed+112, 0))
		s.d.e.SetFloats(mkt.floats(goldSeed+113, 0))
		s.d.e.SetAdv10(mkt.adv10(goldSeed+114, 0))
		s.d.drainCtrl()
		s.opSession(core.SessionPre)
		s.d.e.SetPrevAhHigh(mkt.ahHighs(goldSeed+115, 0))
		s.d.e.SetDailyLevels(mkt.levels(goldSeed+116, 0))
		s.d.e.SetPrevLows(mkt.prevLows(goldSeed+117, 0))
		s.d.drainCtrl()
	})
	s.op(goldMs(20, 9, 30, 0, 100), "session regular", func() { s.opSession(core.SessionRegular) })
	s.op(goldMs(20, 9, 30, 10, 0), "reads", s.opReads)
	s.op(goldMs(20, 9, 34, 0, 0), "prefill pre", func() { s.d.e.SeedFrozen(core.SessionPre, mkt.frozen(goldSeed+118)); s.d.drainCtrl() })
	s.op(goldMs(20, 9, 38, 0, 0), "reconnect seed", func() { s.opSeed(func(i int) bool { return i%3 == 0 }, func(int) float64 { return 1.02 }) })
	s.op(goldMs(20, 10, 59, 50, 0), "closed (restart)", func() { s.opSession(core.SessionClosed) }) // regular -> closed: collects, freezes nothing
	s.op(goldMs(20, 11, 0, 0, 500), "regular (restart)", func() { s.opSession(core.SessionRegular) }) // closed -> regular: a scope reset, no freeze
	s.op(goldMs(20, 11, 5, 0, 0), "reads", s.opReads)
	s.op(goldMs(20, 16, 0, 0, 40), "session post", func() { s.opSession(core.SessionPost) })
	s.op(goldMs(20, 16, 0, 30, 0), "reads", s.opReads)
	s.op(goldMs(21, 3, 59, 30, 0), "seed day 2", func() {
		for _, tk := range mkt.tk {
			if tk.px > 0 {
				s.d.seedClose(tk.sym, tk.px)
			}
		}
	})
	s.op(goldMs(21, 4, 0, 5, 0), "pre (post -> pre)", func() { s.opSession(core.SessionPre) }) // a new day without a close in between
	s.op(goldMs(21, 4, 2, 0, 0), "reads", s.opReads)
	return s
}

// goldRunAll plays both scenarios into rec.
func goldRunAll(tb testing.TB, rec *goldRec) {
	tb.Helper()
	dildopb.ResetLive() // the tuning panel's global: the defaults
	if t, ok := tb.(*testing.T); ok {
		t.Cleanup(dildopb.ResetLive)
	}
	rec.comment("scenario main: 600 tickers, 2026-10-20 03:59-04:45, 09:20-10:15, 15:50-16:15, 19:55-20:01 ET and 2026-10-21 03:59-04:10")
	goldMain(tb, rec).run()
	rec.comment("scenario restart: 160 tickers, a late start, a mid-day restart and a new day without a close")
	goldRestart(tb, rec).run()
}

