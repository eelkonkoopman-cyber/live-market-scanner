// GOLDEN EQUIVALENCE TEST. A deterministic synthetic market (golden_market_test.go)
// is pushed through the engine SYNCHRONOUSLY - no shard goroutines: every agg,
// 1 Hz tick, snapshot request and control op is executed by this goroutine, in a
// fixed order, against a fake clock - and the output of every snapshot is
// fingerprinted: every field of every core.Row (rows sorted by symbol, floats as
// their bits, nil pointers distinct from values, nil slices distinct from empty
// ones), the snapshot's Gen / AsOf / Sess, its Index, and the alerts the judges
// hand off (DildoHits, SignalHits), the session-boundary snapshots, and the
// controlled reads (Curves, SessionBars, PmVolLeaders, InPlayLeaders). The
// fingerprints live in testdata/golden_snapshots.txt, generated by the engine as
// it stood BEFORE the performance overhaul: a change that alters any output
// fails at the first step that shows it.
//
//	go test ./internal/engine -run TestGolden                       verify
//	go test ./internal/engine -run TestGolden -update-golden        regenerate (only for an intended behaviour change)
//	GOLDEN_DUMP=<dir> go test ./internal/engine -run TestGolden     also write every step's full rows to <dir>/step-N.jsonl
//	GOLDEN_DUMP_EVERY=5                                             ... but only every 5th step
//	GOLDEN_REF=<dir>                                                on a mismatch, diff the step's rows against <dir>/step-N.jsonl (a dump of the reference engine) and name the symbol and fields
//
// What the driver touches inside the package (a refactor that moves these has
// to move this file with it): shard.onAgg / onTick / snapshot / onCtrl / ctrl,
// Engine.newSnapReq / assembleSnapshot / refreshEtOff / shards / mask / session /
// tracked / loc / now, shardIdx. The public inputs are driven through the same
// Engine methods cmd/scanner and internal/schedule call.
//
// Floats are produced by + - * / and rounding only, and compared as bits, so the
// golden file is for amd64 (an architecture that fuses multiply-add would differ).

var goldUpdate = flag.Bool("update-golden", false, "regenerate internal/engine/testdata/golden_snapshots.txt from the current engine")

const goldFile = "testdata/golden_snapshots.txt"

// ─── driver ─────────────────────────────────────────────────────────────────

// goldDriver runs an Engine without its goroutines.
type goldDriver struct {
	tb    testing.TB
	e     *Engine
	clock atomic.Int64 // the fake wall clock, epoch ms
	gen   uint64
	reply chan []core.Row
}

// goldOptions turns every judge on.
func goldOptions() Options {
	return Options{TickHz: 10, Dildo: true, Climax: true, Bbs: true, Ignition: true, EmaVwap: true, VolBreak: true, SignalLog: true}
}

func newGoldDriver(tb testing.TB, opts Options, startMs int64) *goldDriver {
	tb.Helper()
	d := &goldDriver{tb: tb}
	d.clock.Store(startMs)
	opts.Now = func() time.Time { return time.UnixMilli(d.clock.Load()) }
	d.e = New(opts)
	d.reply = make(chan []core.Row, len(d.e.shards))
	if d.e.loc.String() != "America/New_York" {
		tb.Fatalf("engine location is %q, want America/New_York (tzdata missing?)", d.e.loc)
	}
	if _, off := time.UnixMilli(startMs).In(d.e.loc).Zone(); off != -4*3600 {
		tb.Fatalf("ET offset at the start is %d s, want -14400 (EDT)", off)
	}
	return d
}

func (d *goldDriver) setClock(ms int64) {
	if ms < d.clock.Load() {
		d.tb.Fatalf("golden driver: clock moved backwards (%d -> %d)", d.clock.Load(), ms)
	}
	d.clock.Store(ms)
}

// agg routes one aggregate exactly as Engine.Apply does, minus the channel.
func (d *goldDriver) agg(a core.Agg) { d.e.shards[shardIdx(a.Sym, d.e.mask)].onAgg(a) }

// tick is one wall second of runClock: refresh the ET offset, then every shard.
func (d *goldDriver) tick(sec int64) {
	d.e.refreshEtOff()
	for _, sh := range d.e.shards {
		sh.onTick(sec)
	}
}

// snapshot is one merger tick at the current clock: every shard in order, then
// the assembled snapshot.
func (d *goldDriver) snapshot() *core.MetricSnapshot {
	d.gen++
	now := time.UnixMilli(d.clock.Load())
	req := d.e.newSnapReq(now, d.reply)
	rows := make([]core.Row, 0, d.e.tracked.Load())
	for _, sh := range d.e.shards {
		rows = append(rows, sh.snapshot(req)...)
	}
	return d.e.assembleSnapshot(d.gen, now.UnixMilli(), req.sess, rows)
}

// drainCtrl executes every queued control op, shard by shard, in queue order.
func (d *goldDriver) drainCtrl() {
	for _, sh := range d.e.shards {
		for {
			select {
			case fn := <-sh.ctrl:
				sh.onCtrl(fn)
			default:
				goto next
			}
		}
	next:
	}
}

// call runs fn - an Engine method that BLOCKS until every shard has answered a
// control op (Curves, SessionBars, PmVolLeaders, InPlayLeaders) - on its own
// goroutine and plays the shards on this one.
func (d *goldDriver) call(fn func()) {
	done := make(chan struct{})
	go func() { defer close(done); fn() }()
	for i, sh := range d.e.shards {
		select {
		case f := <-sh.ctrl:
			sh.onCtrl(f)
		case <-time.After(30 * time.Second):
			d.tb.Fatalf("golden driver: shard %d never got its control op", i)
		}
	}
	select {
	case <-done:
	case <-time.After(30 * time.Second):
		d.tb.Fatalf("golden driver: a blocking engine call never returned")
	}
}

// seed and the other single-shot control setters drain after every call: the
// ctrl channels hold 64 ops, a few hundred seeds would block.
func (d *goldDriver) seed(s core.Seed) { d.e.Seed(s); d.drainCtrl() }
func (d *goldDriver) seedClose(sym string, prev float64) {
	d.e.SeedClose(sym, prev)
	d.drainCtrl()
}

// setSession changes the session and plays the boundary op; the boundary's
// whole-market snapshot (when the engine collects one) is returned.
func (d *goldDriver) setSession(s core.Session) (core.SessionSnapshot, bool) {
	old := core.Session(d.e.session.Load())
	collect := s != old && (old == core.SessionPre || old == core.SessionRegular || old == core.SessionPost)
	d.e.SetSession(s)
	d.drainCtrl()
	if !collect {
		return core.SessionSnapshot{}, false
	}
	select {
	case ss := <-d.e.SessionSnapshots():
		return ss, true
	case <-time.After(30 * time.Second):
		d.tb.Fatalf("golden driver: no session snapshot for %v -> %v", old, s)
	}
	return core.SessionSnapshot{}, false
}

// ─── canonical encoding ─────────────────────────────────────────────────────

// goldNaN is the one bit pattern every NaN encodes as: a Null is a Null whatever
// payload and sign the arithmetic that produced it left on it. Everything else
// (-0 vs +0, +Inf, every mantissa bit) is encoded as is.
var goldNaN = math.Float64bits(math.NaN())

// goldAppend appends the canonical bytes of v: every field of every struct in
// declaration order, ints as 8 bytes, floats as their bits, strings and slices
// length-prefixed (a nil slice distinct from an empty one), pointers as a
// presence byte and the value, maps in key order. An unsupported kind panics, so
// a new field type in core.Row cannot slip through unfingerprinted.
func goldAppend(b []byte, v reflect.Value) []byte {
	switch v.Kind() {
	case reflect.Bool:
		if v.Bool() {
			return append(b, 1)
		}
		return append(b, 0)
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return binary.LittleEndian.AppendUint64(b, uint64(v.Int()))
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return binary.LittleEndian.AppendUint64(b, v.Uint())
	case reflect.Float32, reflect.Float64:
		f := v.Float()
		bits := math.Float64bits(f)
		if f != f {
			bits = goldNaN
		}
		return binary.LittleEndian.AppendUint64(b, bits)
	case reflect.String:
		s := v.String()
		b = binary.LittleEndian.AppendUint32(b, uint32(len(s)))
		return append(b, s...)
	case reflect.Pointer:
		if v.IsNil() {
			return append(b, 0)
		}
		return goldAppend(append(b, 1), v.Elem())
	case reflect.Slice:
		if v.IsNil() {
			return append(b, 0xff, 0xff, 0xff, 0xff)
		}
		b = binary.LittleEndian.AppendUint32(b, uint32(v.Len()))
		for i := 0; i < v.Len(); i++ {
			b = goldAppend(b, v.Index(i))
		}
		return b
	case reflect.Array:
		for i := 0; i < v.Len(); i++ {
			b = goldAppend(b, v.Index(i))
		}
		return b
	case reflect.Struct:
		for i := 0; i < v.NumField(); i++ {
			b = goldAppend(b, v.Field(i))
		}
		return b
	case reflect.Map:
		keys := v.MapKeys()
		sort.Slice(keys, func(i, j int) bool { return keys[i].String() < keys[j].String() })
		b = binary.LittleEndian.AppendUint32(b, uint32(len(keys)))
		for _, k := range keys {
			b = goldAppend(goldAppend(b, k), v.MapIndex(k))
		}
		return b
	}
	panic("golden: unsupported kind " + v.Kind().String() + " in a fingerprinted value")
}

// goldSum is the SHA-256 of the canonical encoding of vals.
func goldSum(vals ...any) string {
	var b []byte
	for _, v := range vals {
		b = goldAppend(b, reflect.ValueOf(v))
	}
	s := sha256.Sum256(b)
	return hex.EncodeToString(s[:])
}

// goldJSON appends v as JSON for the dump: floats in their shortest exact form
// (NaN as null, infinities as strings), a Bar as [t,o,h,l,c,v]. With omit, a
// top-level Null float and nil pointer are left out (an absent key is a Null).
func goldJSON(b []byte, v reflect.Value, omit bool) []byte {
	switch v.Kind() {
	case reflect.Bool:
		return strconv.AppendBool(b, v.Bool())
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return strconv.AppendInt(b, v.Int(), 10)
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return strconv.AppendUint(b, v.Uint(), 10)
	case reflect.Float32, reflect.Float64:
		f := v.Float()
		switch {
		case f != f:
			return append(b, "null"...)
		case math.IsInf(f, 1):
			return append(b, `"+Inf"`...)
		case math.IsInf(f, -1):
			return append(b, `"-Inf"`...)
		}
		return strconv.AppendFloat(b, f, 'g', -1, 64)
	case reflect.String:
		return strconv.AppendQuote(b, v.String())
	case reflect.Pointer:
		if v.IsNil() {
			return append(b, "null"...)
		}
		return goldJSON(b, v.Elem(), false)
	case reflect.Slice, reflect.Array:
		if v.Kind() == reflect.Slice && v.IsNil() {
			return append(b, "null"...)
		}
		b = append(b, '[')
		for i := 0; i < v.Len(); i++ {
			if i > 0 {
				b = append(b, ',')
			}
			b = goldJSON(b, v.Index(i), false)
		}
		return append(b, ']')
	case reflect.Struct:
		if v.Type() == reflect.TypeOf(core.Bar{}) {
			bar := v.Interface().(core.Bar)
			b = append(b, '[')
			b = strconv.AppendInt(b, bar.T, 10)
			for _, f := range [...]float64{bar.O, bar.H, bar.L, bar.C} {
				b = append(b, ',')
				b = strconv.AppendFloat(b, f, 'g', -1, 64)
			}
			b = append(b, ',')
			b = strconv.AppendInt(b, bar.V, 10)
			return append(b, ']')
		}
		b = append(b, '{')
		first := true
		t := v.Type()
		for i := 0; i < v.NumField(); i++ {
			f := v.Field(i)
			if omit && ((f.Kind() == reflect.Float64 && f.Float() != f.Float()) || (f.Kind() == reflect.Pointer && f.IsNil())) {
				continue
			}
			if !first {
				b = append(b, ',')
			}
			first = false
			b = strconv.AppendQuote(b, t.Field(i).Name)
			b = append(b, ':')
			b = goldJSON(b, f, false)
		}
		return append(b, '}')
	case reflect.Map:
		keys := v.MapKeys()
		sort.Slice(keys, func(i, j int) bool { return keys[i].String() < keys[j].String() })
		b = append(b, '{')
		for i, k := range keys {
			if i > 0 {
				b = append(b, ',')
			}
			b = strconv.AppendQuote(b, k.String())
			b = append(b, ':')
			b = goldJSON(b, v.MapIndex(k), false)
		}
		return append(b, '}')
	}
	panic("golden: unsupported kind " + v.Kind().String() + " in a dumped value")
}

// goldOrder returns the positions of rows sorted by symbol.
func goldOrder(rows []core.Row) []int {
	idx := make([]int, len(rows))
	for i := range idx {
		idx[i] = i
	}
	sort.Slice(idx, func(a, b int) bool { return rows[idx[a]].Sym < rows[idx[b]].Sym })
	return idx
}

// goldSnapSum fingerprints a snapshot, or says what is inconsistent about it.
// cover (len = number of Row fields) is marked for every field that, in some
// row, differs from def (a pristine row), so the market can be checked for
// exercising each field.
func goldSnapSum(snap *core.MetricSnapshot, cover []bool, def *core.Row) (string, error) {
	rows := snap.Rows
	idx := goldOrder(rows)
	if len(snap.Index) != len(rows) {
		return "", fmt.Errorf("Index has %d entries for %d rows", len(snap.Index), len(rows))
	}
	for i := range rows {
		if got, ok := snap.Index[rows[i].Sym]; !ok || got != i {
			return "", fmt.Errorf("Index[%q] = %d (present %v), the row is at %d", rows[i].Sym, got, ok, i)
		}
	}
	for k := 1; k < len(idx); k++ {
		if rows[idx[k]].Sym == rows[idx[k-1]].Sym {
			return "", fmt.Errorf("duplicate symbol %q", rows[idx[k]].Sym)
		}
	}
	h := sha256.New()
	var b []byte
	b = binary.LittleEndian.AppendUint64(b, snap.Gen)
	b = binary.LittleEndian.AppendUint64(b, uint64(snap.AsOf))
	b = append(b, byte(snap.Sess))
	b = binary.LittleEndian.AppendUint64(b, uint64(len(rows)))
	h.Write(b)
	var dv, scratch []byte
	defV := reflect.ValueOf(def).Elem()
	for _, i := range idx {
		b = b[:0]
		rv := reflect.ValueOf(&rows[i]).Elem()
		if cover != nil {
			for f := 0; f < rv.NumField(); f++ {
				if cover[f] {
					continue
				}
				scratch = goldAppend(scratch[:0], rv.Field(f))
				dv = goldAppend(dv[:0], defV.Field(f))
				if !bytes.Equal(scratch, dv) {
					cover[f] = true
				}
			}
		}
		b = goldAppend(b, rv)
		h.Write(b)
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// goldDumpSnap renders a snapshot for GOLDEN_DUMP: a header line, then one JSON
// object per row sorted by symbol (Null floats and nil pointers omitted).
func goldDumpSnap(step int, snap *core.MetricSnapshot) []byte {
	var b []byte
	b = fmt.Appendf(b, `{"step":%d,"gen":%d,"asOf":%d,"sess":%q,"rows":%d}`+"\n", step, snap.Gen, snap.AsOf, snap.Sess.String(), len(snap.Rows))
	for _, i := range goldOrder(snap.Rows) {
		b = goldJSON(b, reflect.ValueOf(&snap.Rows[i]).Elem(), true)
		b = append(b, '\n')
	}
	return b
}

// goldDiffDump names the first symbol whose dumped row differs between two
// dumps of the same step, and the fields that differ.
func goldDiffDump(want, got []byte) string {
	wl := bytes.Split(bytes.TrimRight(want, "\n"), []byte("\n"))
	gl := bytes.Split(bytes.TrimRight(got, "\n"), []byte("\n"))
	if len(wl) != len(gl) {
		return fmt.Sprintf("the reference dump has %d lines, this run %d (rows differ in number)", len(wl), len(gl))
	}
	for i := 1; i < len(wl); i++ {
		if bytes.Equal(wl[i], gl[i]) {
			continue
		}
		var wm, gm map[string]json.RawMessage
		_ = json.Unmarshal(wl[i], &wm)
		_ = json.Unmarshal(gl[i], &gm)
		var diffs []string
		keys := map[string]bool{}
		for k := range wm {
			keys[k] = true
		}
		for k := range gm {
			keys[k] = true
		}
		var names []string
		for k := range keys {
			names = append(names, k)
		}
		sort.Strings(names)
		for _, k := range names {
			if !bytes.Equal(wm[k], gm[k]) {
				w, g := string(wm[k]), string(gm[k])
				if w == "" {
					w = "(null)"
				}
				if g == "" {
					g = "(null)"
				}
				diffs = append(diffs, fmt.Sprintf("%s: reference %s, now %s", k, w, g))
			}
		}
		if len(diffs) > 12 {
			diffs = append(diffs[:12], fmt.Sprintf("... and %d more", len(diffs)-12))
		}
		return fmt.Sprintf("first differing row (reference line %d): %s\n    %s", i, gm["Sym"], strings.Join(diffs, "\n    "))
	}
	return "the dumps are identical (the difference is in the header, Gen / AsOf / Sess)"
}

// ─── recorder ───────────────────────────────────────────────────────────────

// goldRec turns the run into fingerprint lines and checks each against the
// golden file as it is produced, failing at the first mismatch.
type goldRec struct {
	tb        testing.TB
	want      []string // expected lines (comments stripped); nil when updating
	lines     []string // the lines produced so far
	file      []string // lines plus comments, for -update-golden
	update    bool
	dumpDir   string
	dumpEvery int
	refDir    string
	step      int

	cover []bool
	def   core.Row
	snaps int

	pendHits []core.DildoHit
	pendSigs []core.SignalHit
	kinds    map[string]int
	sessions map[string]int
}

func newGoldRec(tb testing.TB) *goldRec {
	g := &goldRec{tb: tb, update: *goldUpdate, kinds: map[string]int{}, sessions: map[string]int{}}
	g.dumpDir = os.Getenv("GOLDEN_DUMP")
	g.refDir = os.Getenv("GOLDEN_REF")
	g.dumpEvery = 1
	if s := os.Getenv("GOLDEN_DUMP_EVERY"); s != "" {
		if n, err := strconv.Atoi(s); err == nil && n > 0 {
			g.dumpEvery = n
		}
	}
	if g.dumpDir != "" {
		if err := os.MkdirAll(g.dumpDir, 0o755); err != nil {
			tb.Fatalf("GOLDEN_DUMP: %v", err)
		}
	}
	g.cover = make([]bool, reflect.TypeOf(core.Row{}).NumField())
	g.def = (&tickerState{curveBkt: -1, curveFirst: -1, barHead: -1}).toRow(0, nil, nil, nil, core.SessionClosed)
	if !g.update {
		raw, err := os.ReadFile(goldFile)
		if err != nil {
			tb.Fatalf("%v\nno golden file: generate it with the engine as it should behave: go test ./internal/engine -run TestGolden -update-golden", err)
		}
		for _, l := range strings.Split(strings.ReplaceAll(string(raw), "\r\n", "\n"), "\n") {
			if l != "" && !strings.HasPrefix(l, "#") {
				g.want = append(g.want, l)
			}
		}
	}
	return g
}

func (g *goldRec) comment(format string, args ...any) {
	g.file = append(g.file, "# "+fmt.Sprintf(format, args...))
}

// push records one fingerprint line and compares it. snap (may be nil) is the
// snapshot behind it, for the diff against GOLDEN_REF.
func (g *goldRec) push(line string, snap *core.MetricSnapshot) {
	g.tb.Helper()
	i := len(g.lines)
	g.lines = append(g.lines, line)
	g.file = append(g.file, line)
	if g.update {
		return
	}
	if i >= len(g.want) {
		g.tb.Fatalf("golden: the run produced more steps than %s holds (%d lines); first extra line:\n  %s", goldFile, len(g.want), line)
	}
	if g.want[i] == line {
		return
	}
	msg := fmt.Sprintf("golden MISMATCH at line %d of %s (step %d)\n  want %s\n  got  %s", i+1, goldFile, g.step, g.want[i], line)
	switch {
	case snap != nil && g.refDir != "":
		ref, err := os.ReadFile(filepath.Join(g.refDir, fmt.Sprintf("step-%d.jsonl", g.step)))
		if err != nil {
			msg += fmt.Sprintf("\n  (GOLDEN_REF: %v)", err)
		} else {
			msg += "\n  " + goldDiffDump(ref, goldDumpSnap(g.step, snap))
		}
	case snap != nil:
		msg += "\n  to see which symbol and field differ: dump the reference engine's rows once (GOLDEN_DUMP=<dir>), then re-run this with GOLDEN_REF=<dir>"
	}
	g.tb.Fatal(msg)
}

// snapshot fingerprints one snapshot (and, right after it, the alerts handed
// off since the previous one).
func (g *goldRec) snapshot(snap *core.MetricSnapshot) {
	g.tb.Helper()
	g.step++
	g.snaps++
	sum, err := goldSnapSum(snap, g.cover, &g.def)
	if err != nil {
		g.tb.Fatalf("golden: step %d: inconsistent snapshot: %v", g.step, err)
	}
	g.sessions[snap.Sess.String()]++
	g.push(fmt.Sprintf("step %d asOf %d rows %d sha256 %s", g.step, snap.AsOf, len(snap.Rows), sum), snap)
	if g.dumpDir != "" && g.step%g.dumpEvery == 0 {
		if err := os.WriteFile(filepath.Join(g.dumpDir, fmt.Sprintf("step-%d.jsonl", g.step)), goldDumpSnap(g.step, snap), 0o644); err != nil {
			g.tb.Fatalf("GOLDEN_DUMP: %v", err)
		}
	}
	g.flushEvents(snap)
}

// flushEvents fingerprints the alerts collected since the last flush: each
// channel stable-sorted by symbol (the order tickers of one shard are judged in
// is a map iteration; one ticker's own alerts stay in order).
func (g *goldRec) flushEvents(snap *core.MetricSnapshot) {
	g.tb.Helper()
	if len(g.pendHits) == 0 && len(g.pendSigs) == 0 {
		return
	}
	sort.SliceStable(g.pendHits, func(i, j int) bool { return g.pendHits[i].Sym < g.pendHits[j].Sym })
	sort.SliceStable(g.pendSigs, func(i, j int) bool { return g.pendSigs[i].Sym < g.pendSigs[j].Sym })
	for _, s := range g.pendSigs {
		g.kinds[s.Kind]++
	}
	g.kinds["(dildo hand-off)"] += len(g.pendHits)
	line := fmt.Sprintf("step %d events dildo %d signals %d sha256 %s", g.step, len(g.pendHits), len(g.pendSigs), goldSum(g.pendHits, g.pendSigs))
	g.pendHits, g.pendSigs = g.pendHits[:0], g.pendSigs[:0]
	g.push(line, snap)
	if g.dumpDir != "" && g.step%g.dumpEvery == 0 {
		// the alerts go in a file of their own next to the step's rows
		_ = os.WriteFile(filepath.Join(g.dumpDir, fmt.Sprintf("step-%d.events.jsonl", g.step)), g.lastEvents(), 0o644)
	}
}

func (g *goldRec) lastEvents() []byte { return nil }

// op records the result of a control op as its own step.
func (g *goldRec) op(name, what string, vals ...any) {
	g.tb.Helper()
	g.step++
	g.push(fmt.Sprintf("step %d %s %s sha256 %s", g.step, name, what, goldSum(vals...)), nil)
}

// finish checks the run produced exactly the golden file's lines and, when
// updating, writes it.
func (g *goldRec) finish(header ...string) {
	g.tb.Helper()
	if g.update {
		var sb strings.Builder
		for _, h := range header {
			sb.WriteString("# " + h + "\n")
		}
		for _, l := range g.file {
			sb.WriteString(l + "\n")
		}
		if err := os.MkdirAll(filepath.Dir(goldFile), 0o755); err != nil {
			g.tb.Fatal(err)
		}
		if err := os.WriteFile(goldFile, []byte(sb.String()), 0o644); err != nil {
			g.tb.Fatal(err)
		}
		g.tb.Logf("wrote %s: %d lines", goldFile, len(g.lines))
		return
	}
	if len(g.lines) != len(g.want) {
		g.tb.Fatalf("golden: the run produced %d lines, %s holds %d", len(g.lines), goldFile, len(g.want))
	}
}

// ─── scenario machinery ─────────────────────────────────────────────────────

type goldWin struct{ from, to int64 } // epoch seconds [from, to)
type goldSpan struct{ from, to int64 }

type goldOp struct {
	atMs int64
	name string
	fn   func()
}

// goldSim plays one scenario: windows of simulated seconds with a fake clock,
// the market's aggregates, the scripted control ops, and a snapshot cadence
// built to hit the cases a snapshot cache would get wrong.
type goldSim struct {
	tb      testing.TB
	d       *goldDriver
	mkt     *goldMarket
	rec     *goldRec
	rng     *goldRand
	wins    []goldWin
	ops     []goldOp
	opIdx   int
	dense   []goldSpan // a snapshot (or more) every second
	down    []goldSpan // the feed delivers nothing (disconnected)
	noTick  []goldSpan // the 1 Hz clock is dropped
	pSparse float64    // chance of a snapshot in any other second
}

func goldIn(spans []goldSpan, sec int64) bool {
	for _, s := range spans {
		if sec >= s.from && sec < s.to {
			return true
		}
	}
	return false
}

// goldSec / goldMs: an instant of 2026-10-<day> h:m:s ET (EDT, UTC-4) as epoch
// seconds / ms.
func goldSec(day, h, m, s int) int64 {
	return time.Date(2026, 10, day, h+4, m, s, 0, time.UTC).Unix()
}
func goldMs(day, h, m, s, ms int) int64 { return goldSec(day, h, m, s)*1000 + int64(ms) }

func goldMinutes(wins []goldWin) []int64 {
	var out []int64
	for _, w := range wins {
		for m := w.from / 60; m <= (w.to-1)/60; m++ {
			out = append(out, m)
		}
	}
	return out
}

// goldBoundary: sec is exactly the start of a 5-minute bucket.
func goldBoundary(sec int64) bool { return goldSecOfDay(sec)%300 == 0 }

// op schedules fn at the given instant.
func (s *goldSim) op(atMs int64, name string, fn func()) {
	s.ops = append(s.ops, goldOp{atMs: atMs, name: name, fn: fn})
}

const (
	goldEvTick = iota
	goldEvOp
	goldEvAgg
	goldEvSnap
)

type goldEv struct {
	at, kind, seq int
	agg           core.Agg
	op            *goldOp
}

// snapPlan is the second's snapshot offsets (ms into the second) and where its
// aggregates land: 0 spread over the second, 1 all up front (nothing between the
// snapshots), 2 all at the end (nothing before the snapshots).
func (s *goldSim) snapPlan(sec int64) (offs []int, mode int) {
	r := s.rng
	switch {
	case goldIn(s.dense, sec):
		switch p := r.f(); {
		case p < 0.30:
			offs = []int{r.intn(1000)}
		case p < 0.43:
			offs, mode = []int{0, 300, 700}, 1
		case p < 0.50:
			offs, mode = []int{0, 300, 700}, 2
		case p < 0.62:
			offs = []int{100, 450, 800} // aggs arrive between them
		case p < 0.70:
			offs = []int{0}
		case p < 0.78:
			offs, mode = []int{999}, 1
		case p < 0.86:
			offs = []int{500, 500} // two snapshots of the same instant
		case p < 0.89:
			offs = []int{0, 100, 200, 300, 400, 500, 600, 700, 800, 900} // the real 10 Hz cadence
		default:
			offs, mode = []int{0, 0}, 1
		}
	case r.chance(s.pSparse):
		offs = []int{r.intn(1000)}
	}
	if goldBoundary(sec) { // exactly on a bucket boundary
		offs = append(offs, 0)
	}
	if goldBoundary(sec + 1) { // the last millisecond of the bucket before it
		offs = append(offs, 999)
	}
	sort.Ints(offs)
	return offs, mode
}

// second plays wall second sec: the clock tick, the aggregates that arrive,
// the scripted ops due, and the snapshots.
func (s *goldSim) second(sec int64) {
	ms0 := sec * 1000
	aggs := s.mkt.second(sec) // always generated, so the market advances; dropped while the feed is down
	if goldIn(s.down, sec) {
		aggs = nil
	}
	offs, mode := s.snapPlan(sec)
	var evs []goldEv
	add := func(e goldEv) { e.seq = len(evs); evs = append(evs, e) }
	if !goldIn(s.noTick, sec) {
		add(goldEv{at: 0, kind: goldEvTick})
	}
	for s.opIdx < len(s.ops) && s.ops[s.opIdx].atMs < ms0+1000 {
		op := &s.ops[s.opIdx]
		s.opIdx++
		add(goldEv{at: int(op.atMs - ms0), kind: goldEvOp, op: op})
	}
	// arrival order is not the generation order
	for i := len(aggs) - 1; i > 0; i-- {
		j := s.rng.intn(i + 1)
		aggs[i], aggs[j] = aggs[j], aggs[i]
	}
	for _, a := range aggs {
		at := 0
		switch mode {
		case 0:
			at = 1 + s.rng.intn(998)
		case 2:
			at = 999
		}
		add(goldEv{at: at, kind: goldEvAgg, agg: a})
	}
	for _, o := range offs {
		add(goldEv{at: o, kind: goldEvSnap})
	}
	sort.SliceStable(evs, func(i, j int) bool {
		if evs[i].at != evs[j].at {
			return evs[i].at < evs[j].at
		}
		return evs[i].kind < evs[j].kind
	})
	for _, e := range evs {
		switch e.kind {
		case goldEvTick:
			s.d.setClock(ms0)
			s.d.tick(sec)
			s.drainEvents()
		case goldEvOp:
			s.d.setClock(e.op.atMs)
			e.op.fn()
			s.drainEvents()
		case goldEvAgg:
			s.d.agg(e.agg)
		case goldEvSnap:
			s.d.setClock(ms0 + int64(e.at))
			s.snap()
		}
	}
	s.drainEvents()
}

// snap takes one snapshot at the current clock and fingerprints it.
func (s *goldSim) snap() {
	s.drainEvents()
	s.rec.snapshot(s.d.snapshot())
}

// drainEvents moves the alerts the judges have handed off into the recorder.
func (s *goldSim) drainEvents() {
	for {
		select {
		case h := <-s.d.e.DildoHits():
			s.rec.pendHits = append(s.rec.pendHits, h)
		case h := <-s.d.e.SignalHits():
			s.rec.pendSigs = append(s.rec.pendSigs, h)
		default:
			return
		}
	}
}

func (s *goldSim) run() {
	for _, w := range s.wins {
		s.runOpsBefore(w.from * 1000)
		for sec := w.from; sec < w.to; sec++ {
			s.second(sec)
		}
	}
	s.runOpsBefore(math.MaxInt64)
	s.drainEvents()
	s.rec.step++
	s.rec.flushEvents(nil) // alerts after the last snapshot
	if n := s.d.e.DildoDrops() + s.d.e.SignalDrops() + s.d.e.SessionSnapshotDrops(); n != 0 {
		s.tb.Fatalf("golden: %d alerts / session snapshots were dropped (a hand-off buffer overflowed); the fingerprint would depend on it", n)
	}
}

func (s *goldSim) runOpsBefore(ms int64) {
	for s.opIdx < len(s.ops) && s.ops[s.opIdx].atMs < ms {
		op := s.ops[s.opIdx]
		s.opIdx++
		s.d.setClock(op.atMs)
		op.fn()
		s.drainEvents()
	}
}

// ─── the ops a scenario schedules ───────────────────────────────────────────

func (s *goldSim) opSession(sess core.Session) {
	ss, ok := s.d.setSession(sess)
	if !ok {
		return
	}
	rows := append([]core.SessionSnapshotRow(nil), ss.Rows...)
	sort.Slice(rows, func(i, j int) bool { return rows[i].Sym < rows[j].Sym })
	s.rec.op("sesssnap", fmt.Sprintf("%s %s rows %d", ss.Date, ss.Session, len(rows)), ss.Date, uint8(ss.Session), rows)
}

// opReads plays the controlled reads: the volume curves, the session bars, the
// pre-market leaders and the in-play ranking.
func (s *goldSim) opReads() {
	lb := bucketOf(time.UnixMilli(s.d.clock.Load()).In(s.d.e.loc))
	var curves map[string][]int64
	s.d.call(func() { curves = s.d.e.Curves(lb) })
	s.rec.op("curves", fmt.Sprintf("lb %d keys %d", lb, len(curves)), curves)
	var bars map[string][]core.DailyBar
	s.d.call(func() { bars = s.d.e.SessionBars() })
	s.rec.op("sessionbars", fmt.Sprintf("keys %d", len(bars)), bars)
	var pm []core.PmVolEntry
	s.d.call(func() { pm = s.d.e.PmVolLeaders(1, 25) })
	s.rec.op("pmvol", fmt.Sprintf("min 1 limit 25 n %d", len(pm)), pm)
	var pm0 []core.PmVolEntry
	s.d.call(func() { pm0 = s.d.e.PmVolLeaders(0.05, 0) })
	s.rec.op("pmvol", fmt.Sprintf("min 0.05 limit 0 n %d", len(pm0)), pm0)
	var ip []core.InPlayEntry
	s.d.call(func() { ip = s.d.e.InPlayLeaders(30) })
	s.rec.op("inplay", fmt.Sprintf("limit 30 n %d", len(ip)), ip)
	s.rec.op("tracked", strconv.Itoa(s.d.e.Tracked()), s.d.e.Tracked())
}

// opSeed seeds the tickers pick selects (the ingest snapshot, at start or on a
// reconnect); distort scales the seeded day volume against the engine's own.
func (s *goldSim) opSeed(pick func(i int) bool, distort func(i int) float64) {
	now := s.d.clock.Load()
	for i, tk := range s.mkt.tk {
		if pick(i) {
			s.d.seed(tk.seed(now, distort(i)))
		}
	}
}

// opSwap replaces the reference tables named (b: baseline, f: floats, t:
// secTypes) and takes a snapshot before and after at the same clock (dt ms
// later for the second one): nothing else changes between them.
func (s *goldSim) opSwap(what string, variant int, dt int64, seed uint64) {
	s.snap()
	if strings.Contains(what, "b") {
		old := s.d.e.Baseline()
		if variant%2 == 0 {
			s.d.e.SetBaseline(s.mkt.baseline(seed, variant))
		} else {
			// the nightly recompute's shape: a copy with a slice of the tickers replaced (and some dropped)
			part := s.mkt.baseline(seed, variant)
			var syms []string
			for i, tk := range s.mkt.tk {
				if i%5 == 1 {
					syms = append(syms, tk.sym)
				}
			}
			s.d.e.SetBaseline(old.With(part, syms))
		}
	}
	if strings.Contains(what, "f") {
		s.d.e.SetFloats(s.mkt.floats(seed+1, variant))
	}
	if strings.Contains(what, "t") {
		s.d.e.SetSecTypes(s.mkt.types(seed+2, variant))
	}
	s.d.setClock(s.d.clock.Load() + dt)
	s.snap()
}

// opCtrl runs fn - control ops on the shards - between two snapshots at the
// same clock with nothing else in between, so a row the snapshot path reused
// across the op instead of rebuilding would show its old values.
func (s *goldSim) opCtrl(fn func()) {
	s.snap()
	fn()
	s.d.drainCtrl()
	s.snap()
}

