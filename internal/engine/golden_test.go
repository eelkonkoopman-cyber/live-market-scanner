func TestGoldenSnapshots(t *testing.T) {
	start := time.Now()
	rec := newGoldRec(t)
	goldRunAll(t, rec)
	rec.finish(
		"Golden fingerprints of internal/engine: one line per snapshot step (rows sorted by symbol, every core.Row field, Gen/AsOf/Sess, Index),",
		"per hand-off batch (DildoHits / SignalHits), per session-boundary snapshot and per controlled read (Curves, SessionBars, PmVolLeaders, InPlayLeaders).",
		"Generated by TestGoldenSnapshots -update-golden from the engine BEFORE the performance overhaul. Do not edit by hand.",
	)

	// the market must exercise every field the engine writes
	t.Logf("%d snapshot steps, %d lines, %s", rec.snaps, len(rec.lines), time.Since(start).Round(time.Millisecond))
	t.Logf("alerts handed off: %v", rec.kinds)
	t.Logf("snapshots by session: %v", rec.sessions)
	rt := reflect.TypeOf(core.Row{})
	var missing, unused []string
	for i, c := range rec.cover {
		name := rt.Field(i).Name
		switch {
		case !c && !goldOverlay[name]:
			missing = append(missing, name)
		case c && goldOverlay[name]:
			unused = append(unused, name)
		}
	}
	if len(missing) > 0 {
		t.Errorf("the synthetic market never populated these engine-written Row fields (so the golden test would not see them change): %v", missing)
	}
	if len(unused) > 0 {
		t.Errorf("these Row fields are listed as scanner overlays but the engine populated them: %v", unused)
	}
	for _, kind := range []string{"(dildo hand-off)", "dildo", "power", "climax", "bottom", "climaxFail", "bbs", "ignition"} { // vwapBull/vwapBear: history-gated to the scan universe (emavwap.go); the synthetic market has none, the Ev* row fields still cover the cross
		if rec.kinds[kind] == 0 {
			t.Errorf("the synthetic market never produced a %q alert", kind)
		}
	}
}

// TestGoldenFingerprintSeesEveryField perturbs each field of a populated Row in
// turn (and each field of a Bar, and a nil <-> value pointer, and a nil <->
// empty slice) and requires the snapshot fingerprint to change: the reflection
// walk is the safety net, so it is itself tested.
func TestGoldenFingerprintSeesEveryField(t *testing.T) {
	mk := func() *core.MetricSnapshot {
		so := int64(5)
		rows := []core.Row{{Sym: "AAA", Bars: []core.Bar{{T: 1, O: 2, H: 3, L: 1, C: 2, V: 7}}, ShsOut: &so}, {Sym: "BBB"}}
		return &core.MetricSnapshot{Gen: 3, AsOf: 4, Sess: core.SessionRegular, Rows: rows, Index: map[string]int{"AAA": 0, "BBB": 1}}
	}
	def := core.Row{}
	base, err := goldSnapSum(mk(), nil, &def)
	if err != nil {
		t.Fatal(err)
	}
	rv := reflect.TypeOf(core.Row{})
	for i := 0; i < rv.NumField(); i++ {
		f := rv.Field(i)
		snap := mk()
		fv := reflect.ValueOf(&snap.Rows[1]).Elem().Field(i)
		switch fv.Kind() {
		case reflect.Float64:
			fv.SetFloat(1.5)
		case reflect.Int, reflect.Int64, reflect.Uint8:
			if fv.Kind() == reflect.Uint8 {
				fv.SetUint(2)
			} else {
				fv.SetInt(9)
			}
		case reflect.Bool:
			fv.SetBool(true)
		case reflect.String:
			if f.Name == "Sym" {
				continue // the key; covered below
			}
			fv.SetString("x")
		case reflect.Pointer:
			v := int64(1)
			fv.Set(reflect.ValueOf(&v))
		case reflect.Slice:
			fv.Set(reflect.ValueOf([]core.Bar{}))
		default:
			t.Fatalf("Row.%s has kind %v: teach the fingerprint test about it", f.Name, fv.Kind())
		}
		got, err := goldSnapSum(snap, nil, &def)
		if err != nil {
			t.Fatal(err)
		}
		if got == base {
			t.Errorf("fingerprint ignores Row.%s", f.Name)
		}
	}
	// nested fields
	bt := reflect.TypeOf(core.Bar{})
	for i := 0; i < bt.NumField(); i++ {
		snap := mk()
		fv := reflect.ValueOf(&snap.Rows[0].Bars[0]).Elem().Field(i)
		switch fv.Kind() {
		case reflect.Float64:
			fv.SetFloat(fv.Float() + 0.25)
		default:
			fv.SetInt(fv.Int() + 1)
		}
		if got, _ := goldSnapSum(snap, nil, &def); got == base {
			t.Errorf("fingerprint ignores Bar.%s", bt.Field(i).Name)
		}
	}
	// -0 vs +0, NaN payloads, the snapshot header, the Index
	snap := mk()
	snap.Rows[1].Last = math.Copysign(0, -1)
	if got, _ := goldSnapSum(snap, nil, &def); got == base {
		t.Error("fingerprint ignores the sign of zero")
	}
	a, b := mk(), mk()
	a.Rows[1].Last = math.NaN()
	b.Rows[1].Last = math.Float64frombits(0xfff8000000000000)
	sa, _ := goldSnapSum(a, nil, &def)
	sb, _ := goldSnapSum(b, nil, &def)
	if sa != sb {
		t.Error("two NaN payloads must fingerprint alike (a Null is a Null)")
	}
	for name, mut := range map[string]func(*core.MetricSnapshot){
		"Gen":  func(s *core.MetricSnapshot) { s.Gen++ },
		"AsOf": func(s *core.MetricSnapshot) { s.AsOf++ },
		"Sess": func(s *core.MetricSnapshot) { s.Sess = core.SessionPost },
		"Sym":  func(s *core.MetricSnapshot) { s.Rows[1].Sym = "BBC"; s.Index = map[string]int{"AAA": 0, "BBC": 1} },
	} {
		s := mk()
		mut(s)
		if got, err := goldSnapSum(s, nil, &def); err != nil || got == base {
			t.Errorf("fingerprint ignores %s (err %v)", name, err)
		}
	}
	s2 := mk()
	s2.Index["BBB"] = 0
	if _, err := goldSnapSum(s2, nil, &def); err == nil {
		t.Error("an inconsistent Index must be reported")
	}
	// the order rows arrive in does not matter
	s3 := mk()
	s3.Rows[0], s3.Rows[1] = s3.Rows[1], s3.Rows[0]
	s3.Index = map[string]int{"BBB": 0, "AAA": 1}
	if got, _ := goldSnapSum(s3, nil, &def); got != base {
		t.Error("row order must not change the fingerprint")
	}
}
