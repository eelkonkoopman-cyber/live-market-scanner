// GOLDEN VECTORS for IGNITION: the contract between ignition.ts and Go
// internal/ignition (Judge, the code the scanner engine runs market-wide, and
// Evaluate). This test writes/guards src/signals/fixtures/golden/ignition-golden.json
// ({series, paramSets, cases}); internal/ignition/golden_test.go replays the
// SAME series through ignition.Evaluate and internal/engine replays them
// through the engine judge. Notes are TS-only (not in the file).
//
// REGENERATE after an intentional change to ignition.ts or its fixtures:
//   cd web && UPDATE_GOLDEN=1 npx vitest run src/signals/ignition.golden.test.ts
// then run it again without the variable, and `go test ./internal/ignition/`.
import { describe, expect, it } from 'vitest';
import { DEFAULT_IGNITION_PARAMS, evaluateIgnition, type IgnitionParams } from './ignition';
import { belowDayHighBars, bigBodyBars, ncplBars, noVolumeBars, randomIgnitionBars, wideBaseBars } from './ignition.fixtures';
import type { Candle } from '../vendor/blackthorn-charts';

declare const process: { env: Record<string, string | undefined> };
interface NodeFs {
  readFileSync(path: URL, encoding: 'utf8'): string;
  writeFileSync(path: URL, data: string): void;
}
const fsSpec = 'node:fs';
const fs = (await import(/* @vite-ignore */ fsSpec)) as NodeFs;
const GOLDEN_FILE = new URL('./fixtures/golden/ignition-golden.json', import.meta.url);

const paramSets: Record<string, IgnitionParams> = {
  defaults: DEFAULT_IGNITION_PARAMS,
  loose: { ...DEFAULT_IGNITION_PARAMS, baseBars: 12, maxBasePct: 4, minVolX: 3, minBodyPct: 1.2, maxBodyPct: 6, minDvol: 20_000, cooldownMin: 3 },
};

function buildSeries(): { name: string; bars: { t: number; o: number; h: number; l: number; c: number; v: number }[] }[] {
  const named: [string, Candle[]][] = [
    ['ncpl', ncplBars()],
    ['wideBase', wideBaseBars()],
    ['bigBody', bigBodyBars()],
    ['noVolume', noVolumeBars()],
    ['belowDayHigh', belowDayHighBars()],
  ];
  for (let s = 1; s <= 12; s++) named.push([`random${s}`, randomIgnitionBars(s * 7919, 240)]);
  named.push(['twoDays', [...ncplBars().map((c) => ({ ...c, ts: c.ts - 86_400_000 })), ...ncplBars()]]);
  return named.map(([name, bars]) => ({ name, bars: bars.map((c) => ({ t: c.ts, o: c.open, h: c.high, l: c.low, c: c.close, v: c.volume })) }));
}

const fin = (x: number): number | null => (isFinite(x) ? x : null);

function run() {
  const series = buildSeries();
  const cases: unknown[] = [];
  for (const s of series) {
    const candles: Candle[] = s.bars.map((b) => ({ ts: b.t, open: b.o, high: b.h, low: b.l, close: b.c, volume: b.v }));
    for (const [ps, p] of Object.entries(paramSets)) {
      const cuts = new Set<number>([candles.length]);
      for (const e of evaluateIgnition({ candles, tfMs: 60_000, nowMs: candles[candles.length - 1]!.ts + 600_000, params: p })) {
        const i = candles.findIndex((c) => c.ts === e.ts);
        for (const k of [i, i + 1, i + 2]) if (k > 0 && k <= candles.length) cuts.add(k);
      }
      for (const cut of [...cuts].sort((a, b) => a - b)) {
        const cs = candles.slice(0, cut);
        for (const clock of ['closed', 'forming'] as const) {
          const nowMs = cs[cs.length - 1]!.ts + (clock === 'closed' ? 600_000 : 30_000);
          const ev = evaluateIgnition({ candles: cs, tfMs: 60_000, nowMs, params: p });
          cases.push({
            series: s.name,
            params: ps,
            cut,
            nowMs,
            events: ev.map((e) => ({ ts: e.ts, price: e.price, bodyPct: e.bodyPct, volX: fin(e.volX), dvol: e.dvol, rangePct: e.rangePct, baseHigh: e.baseHigh, dayHigh: e.dayHigh })),
          });
        }
      }
    }
  }
  return { note: 'generated by web/src/signals/ignition.golden.test.ts; never hand-edit', tfMs: 60_000, paramSets, series, cases };
}

describe('ignition golden', () => {
  it('matches the committed golden file', () => {
    const text = JSON.stringify(run(), null, 1) + '\n';
    if (process.env.UPDATE_GOLDEN === '1') fs.writeFileSync(GOLDEN_FILE, text);
    expect(fs.readFileSync(GOLDEN_FILE, 'utf8')).toBe(text);
  });

  it('fires somewhere in the random series too (coverage)', () => {
    const n = buildSeries()
      .filter((s) => s.name.startsWith('random'))
      .reduce((acc, s) => acc + evaluateIgnition({ candles: s.bars.map((b) => ({ ts: b.t, open: b.o, high: b.h, low: b.l, close: b.c, volume: b.v })), tfMs: 60_000, nowMs: Infinity }).length, 0);
    expect(n).toBeGreaterThan(0);
  });
});
