// GOLDEN VECTORS for BOUNCY BALL SHORT: the contract between bouncyShort.ts and
// Go internal/bbs (Analyze, the code the scanner engine runs market-wide, and
// Evaluate). This test writes/guards src/signals/fixtures/golden/bbs-golden.json
// ({series, paramSets, cases}); internal/bbs/golden_test.go replays the SAME
// series through bbs.Evaluate and internal/engine replays them through the
// engine judge. Notes are TS-only (not in the file).
//
// REGENERATE after an intentional change to bouncyShort.ts or its fixtures:
//   cd web && UPDATE_GOLDEN=1 npx vitest run src/signals/bouncyShort.golden.test.ts
// then run it again without the variable, and `go test ./internal/bbs/`.
import { describe, expect, it } from 'vitest';
import { DEFAULT_BBS_PARAMS, evaluateBbs, type BbsParams } from './bouncyShort';
import { aaoiBars, flatHighsBars, randomBars, stairBars, twoTouchBars } from './bouncyShort.fixtures';
import type { Candle } from '../vendor/blackthorn-charts';

declare const process: { env: Record<string, string | undefined> };
interface NodeFs {
  readFileSync(path: URL, encoding: 'utf8'): string;
  writeFileSync(path: URL, data: string): void;
}
const fsSpec = 'node:fs';
const fs = (await import(/* @vite-ignore */ fsSpec)) as NodeFs;
const GOLDEN_FILE = new URL('./fixtures/golden/bbs-golden.json', import.meta.url);

const paramSets: Record<string, BbsParams> = {
  defaults: DEFAULT_BBS_PARAMS,
  loose: { ...DEFAULT_BBS_PARAMS, lookback: 40, supportBandPct: 0.8, minTouches: 2, minSepBars: 2, minBouncePct: 0.3, minLowerHighs: 1, lowerHighPct: 0.05, breakPct: 0.1 },
};

function buildSeries(): { name: string; bars: { t: number; o: number; h: number; l: number; c: number; v: number }[] }[] {
  const named: [string, Candle[]][] = [
    ['aaoi', aaoiBars()],
    ['flatHighs', flatHighsBars()],
    ['stair', stairBars()],
    ['twoTouch', twoTouchBars()],
    ['aaoiGap', [...aaoiBars().slice(0, 69), { ts: aaoiBars()[68]!.ts + 60_000, open: 116.7, high: 116.75, low: 115.0, close: 115.1, volume: 50_000 }]],
  ];
  for (let s = 1; s <= 12; s++) named.push([`random${s}`, randomBars(s * 7919, 240)]);
  // a two-day series: the AAOI day shifted back 24 h, then AAOI
  named.push(['twoDays', [...aaoiBars().map((c) => ({ ...c, ts: c.ts - 86_400_000 })), ...aaoiBars()]]);
  return named.map(([name, bars]) => ({ name, bars: bars.map((c) => ({ t: c.ts, o: c.open, h: c.high, l: c.low, c: c.close, v: c.volume })) }));
}

function run() {
  const series = buildSeries();
  const cases: unknown[] = [];
  for (const s of series) {
    const candles: Candle[] = s.bars.map((b) => ({ ts: b.t, open: b.o, high: b.h, low: b.l, close: b.c, volume: b.v }));
    for (const [ps, p] of Object.entries(paramSets)) {
      const cuts = new Set<number>([candles.length]);
      const full = evaluateBbs({ candles, tfMs: 60_000, nowMs: candles[candles.length - 1]!.ts + 600_000, params: p });
      for (const e of full.events) {
        const i = candles.findIndex((c) => c.ts === e.ts);
        for (const k of [i, i + 1, i + 2]) if (k > 0 && k <= candles.length) cuts.add(k);
      }
      for (const cut of [...cuts].sort((a, b) => a - b)) {
        const cs = candles.slice(0, cut);
        for (const clock of ['closed', 'forming'] as const) {
          const nowMs = cs[cs.length - 1]!.ts + (clock === 'closed' ? 600_000 : 30_000);
          const r = evaluateBbs({ candles: cs, tfMs: 60_000, nowMs, params: p });
          cases.push({
            series: s.name,
            params: ps,
            cut,
            nowMs,
            result: {
              events: r.events.map((e) => ({ ts: e.ts, price: e.price, support: e.support, touches: e.touches, highs: e.highs, firstHigh: e.firstHigh, lastHigh: e.lastHigh })),
              state: r.state,
              support: r.support,
              lastTs: r.lastTs,
            },
          });
        }
      }
    }
  }
  return { note: 'generated by web/src/signals/bouncyShort.golden.test.ts; never hand-edit', tfMs: 60_000, paramSets, series, cases };
}

describe('bbs golden', () => {
  it('matches the committed golden file', () => {
    const text = JSON.stringify(run(), null, 1) + '\n';
    if (process.env.UPDATE_GOLDEN === '1') fs.writeFileSync(GOLDEN_FILE, text);
    expect(fs.readFileSync(GOLDEN_FILE, 'utf8')).toBe(text);
  });
});
